import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { dirname, join } from 'node:path';
const bin = execSync('where playwright',{encoding:'utf8'}).split(/\r?\n/)[0].trim();
const { chromium } = createRequire(import.meta.url)(join(dirname(bin),'..','playwright'));
const [,, theme='light', w='390'] = process.argv;
const b = await chromium.launch();
const c = await b.newContext({viewport:{width:+w,height:700},storageState:'tmp/auth/admin.json'});
await c.addInitScript(t=>localStorage.setItem('gp-ds-theme',t),theme);
const p = await c.newPage();
await p.goto('http://localhost/academy/admin/dashboard',{waitUntil:'networkidle'});
await p.screenshot({path:`tmp/p4/top-${theme}-${w}.png`,clip:{x:0,y:0,width:+w,height:110}});
console.log(await p.evaluate(()=>[...document.querySelectorAll('.button-menu-mobile .lines span')].map(s=>{const cs=getComputedStyle(s);return cs.backgroundColor+' '+cs.height+' '+cs.display+' '+Math.round(s.getBoundingClientRect().width)}).join(' | ')));
await b.close();
